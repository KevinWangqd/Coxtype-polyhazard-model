filter_cor_chunked <- function(X, threshold = 0.75, chunk_size = 5000, max_iter = 5) {
  
  n <- ncol(X)
  message("初始变量数: ", n)
  
  for (iter in 1:max_iter) {
    n_current <- ncol(X)
    
    # 如果变量数已经小于一块的大小，直接对全部做一次筛选
    if (n_current <= chunk_size) {
      message("变量数已降至 ", n_current, "，进行最终筛选")
      accepted <- integer(0)
      for (i in 1:n_current) {
        if (length(accepted) == 0) {
          accepted <- i
        } else {
          cors <- abs(cor(X[, i], X[, accepted, drop = FALSE]))
          if (max(cors) < threshold) accepted <- c(accepted, i)
        }
      }
      X <- X[, accepted, drop = FALSE]
      message("最终保留: ", ncol(X), " 个变量")
      break
    }
    
    message("\n--- 第 ", iter, " 轮 ---")
    message("当前变量数: ", n_current)
    
    # 分块处理
    n_chunks <- ceiling(n_current / chunk_size)
    chunk_results <- vector("list", n_chunks)
    
    for (k in 1:n_chunks) {
      start_idx <- (k-1) * chunk_size + 1
      end_idx <- min(k * chunk_size, n_current)
      
      # 取出当前块
      X_chunk <- X[, start_idx:end_idx, drop = FALSE]
      
      # 块内筛选：按顺序逐个检查
      accepted <- integer(0)
      for (i in 1:ncol(X_chunk)) {
        if (length(accepted) == 0) {
          accepted <- i
        } else {
          cors <- abs(cor(X_chunk[, i], X_chunk[, accepted, drop = FALSE]))
          if (max(cors) < threshold) accepted <- c(accepted, i)
        }
      }
      
      chunk_results[[k]] <- X_chunk[, accepted, drop = FALSE]
      message("  块 ", k, "/", n_chunks, ": ", ncol(X_chunk), " -> ", length(accepted))
    }
    
    # 合并所有块的结果
    X <- do.call(cbind, chunk_results)
    message("本轮保留: ", ncol(X), " 个变量")
    
    # 如果这轮没有减少，停止迭代
    if (ncol(X) == n_current) {
      message("变量数不再减少，停止迭代")
      break
    }
  }
  
  return(X)
}


